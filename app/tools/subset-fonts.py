#!/usr/bin/env python3
"""Rebuild the bundled icon font and the name table from the full Material Symbols font.

    python3 tools/subset-fonts.py [FULL_FONT.ttf] [CODEPOINTS.txt]

Without arguments the two inputs are downloaded from google/material-design-icons
(Apache 2.0). Needs `pip install fonttools`.

Outputs:
  assets/fonts/MaterialSymbolsRounded.ttf   only the glyphs in assets/icon-names.txt,
                                            weight 400-500 and the FILL axis kept
  src/ui/icons.rs                           icon name -> code point table
"""
import pathlib
import sys
import urllib.parse
import urllib.request

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = pathlib.Path(__file__).resolve().parent.parent
BASE = "https://raw.githubusercontent.com/google/material-design-icons/master/variablefont/"
STEM = "MaterialSymbolsRounded[FILL,GRAD,opsz,wght]"


def fetch(suffix: str, target: pathlib.Path) -> pathlib.Path:
    url = BASE + urllib.parse.quote(STEM) + suffix
    print("downloading", url)
    urllib.request.urlretrieve(url, target)
    return target


def main() -> None:
    work = pathlib.Path("/tmp/t4-icons")
    work.mkdir(exist_ok=True)
    full = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else fetch(".ttf", work / "full.ttf")
    codepoints = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else fetch(".codepoints", work / "cp.txt")

    table = {}
    for line in codepoints.read_text().splitlines():
        if line.strip():
            name, code = line.split()
            table[name] = int(code, 16)

    names = [n.strip() for n in (ROOT / "assets/icon-names.txt").read_text().splitlines()
             if n.strip() and not n.startswith("#")]
    missing = [n for n in names if n not in table]
    if missing:
        sys.exit(f"Unknown icon names: {', '.join(missing)}")

    font = TTFont(full)
    options = subset.Options()
    options.layout_features = []          # code points are used directly, no ligatures
    options.name_IDs = [1, 2, 4, 6]
    options.notdef_outline = True
    options.hinting = False
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=[table[n] for n in names])
    subsetter.subset(font)
    # Narrow the variable axes after subsetting: it is much faster on the small font.
    font = instancer.instantiateVariableFont(font, {"GRAD": 0, "opsz": 24, "wght": (400, 500)})
    out = ROOT / "assets/fonts/MaterialSymbolsRounded.ttf"
    font.save(out)
    print(f"wrote {out} ({out.stat().st_size // 1024} KiB, {len(names)} icons)")

    rust = ["// Generated by tools/subset-fonts.py. Do not edit.", "",
            "/// Code point for a Material Symbols icon name.",
            "pub fn glyph(name: &str) -> Option<char> {", "    let code = match name {"]
    for n in sorted(names):
        rust.append(f'        "{n}" => 0x{table[n]:04x},')
    rust += ["        _ => return None,", "    };", "    char::from_u32(code)", "}", "",
             "pub const NAMES: &[&str] = &["]
    rust += [f'    "{n}",' for n in sorted(names)]
    rust += ["];", ""]
    (ROOT / "src/ui/icons.rs").write_text("\n".join(rust))
    print("wrote src/ui/icons.rs")


if __name__ == "__main__":
    main()

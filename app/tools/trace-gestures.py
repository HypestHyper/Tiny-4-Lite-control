#!/usr/bin/env python3
"""Trace the gesture pictures from assets/gesture-reference.png into smooth outlines for the app.

    python3 tools/trace-gestures.py

Needs Pillow, numpy and potracer (`pip install potracer`). Each of the three drawings is cut out, its two
colours (the hand, and the mark: target, magnifier, arrow) are separated, slightly thickened so they hold up
at icon size, softened, and traced to Bézier outlines. Writes src/ui/gesture_paths.rs.
"""
import pathlib

import numpy as np
import potrace
from PIL import Image, ImageFilter

ROOT = pathlib.Path(__file__).resolve().parent.parent
GROUPS = [(126, 412), (556, 832), (930, 1316)]   # x ranges of the three drawings
TOP, BOTTOM = 210, 558
GROW = 7                                          # thickening, in pixels of the doubled picture
NAMES = ["TARGET", "ZOOM", "APART"]


def main() -> None:
    rgb = np.array(Image.open(ROOT / "assets/gesture-reference.png").convert("RGB")).astype(int)
    r, g, b = rgb[..., 0], rgb[..., 1], rgb[..., 2]
    mark = (g - r > 25) & (b - r > 15) & (r < 190)
    hand = (r < 150) & (g < 150) & (b < 170) & (abs(r - g) < 45) & ~mark
    lines = ["// Generated by tools/trace-gestures.py from assets/gesture-reference.png. Do not edit.",
             "// Filled outlines (even-odd) in a 48-unit box: the hand, then its mark.", ""]
    for name, (x0, x1) in zip(NAMES, GROUPS):
        side = int(max(x1 - x0, BOTTOM - TOP) * 1.06)
        left, top = int((x0 + x1) / 2 - side / 2), int((TOP + BOTTOM) / 2 - side / 2)
        for part, mask in (("HAND", hand), ("MARK", mark)):
            img = Image.fromarray((mask * 255).astype("uint8")).crop((left, top, left + side, top + side))
            img = img.resize((side * 2, side * 2), Image.BICUBIC)
            img = img.filter(ImageFilter.MaxFilter(GROW * 2 + 1)).filter(ImageFilter.GaussianBlur(2.5))
            traced = potrace.Bitmap(~(np.array(img) > 110)).trace(turdsize=40, alphamax=1.1, opticurve=True, opttolerance=0.4)
            scale = 48 / (side * 2)
            point = lambda p: f"{p.x * scale:.2f} {p.y * scale:.2f}"
            parts = []
            for curve in traced:
                parts.append("M" + point(curve.start_point))
                for seg in curve.segments:
                    if seg.is_corner:
                        parts.append(f"L{point(seg.c)} L{point(seg.end_point)}")
                    else:
                        parts.append(f"C{point(seg.c1)} {point(seg.c2)} {point(seg.end_point)}")
                parts.append("Z")
            lines.append(f'pub const {name}_{part}: &str = "{" ".join(parts)}";')
    (ROOT / "src/ui/gesture_paths.rs").write_text("\n".join(lines) + "\n")
    print("wrote src/ui/gesture_paths.rs")


if __name__ == "__main__":
    main()
